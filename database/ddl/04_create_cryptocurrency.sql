
SET CURRENT SCHEMA CRYPTO;

-- ============================================================
-- CRYPTOCURRENCY
-- ============================================================

CREATE TABLE CRYPTOCURRENCY (
    ID BIGINT
        GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,

    BLOCKCHAIN_ID BIGINT,
    NAME VARCHAR(150),
    TICKER VARCHAR(30),
    CONTRACT_ADDRESS VARCHAR(255),
    DECIMALS SMALLINT,
    IS_NATIVE SMALLINT,
    ACTIVE SMALLINT NOT NULL DEFAULT 1,

    CONSTRAINT FK_CRYPTOCURRENCY_BLOCKCHAIN
        FOREIGN KEY (BLOCKCHAIN_ID)
        REFERENCES BLOCKCHAIN (ID)
);
