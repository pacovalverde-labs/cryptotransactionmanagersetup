
SET CURRENT SCHEMA CRYPTO;

-- ============================================================
-- MOVEMENT_CRYPTOCURRENCY
-- ============================================================

CREATE TABLE MOVEMENT_CRYPTOCURRENCY (
    ID BIGINT
        GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,

    MOVEMENT_ID BIGINT,
    CRYPTOCURRENCY_ID BIGINT,
    ROLE VARCHAR(30),
    AMOUNT DECIMAL(31,18),
    VALUE_USD DECIMAL(20,8),
    VALUE_EUR DECIMAL(20,8),

    CONSTRAINT FK_MOV_CRYPTO_MOVEMENT
        FOREIGN KEY (MOVEMENT_ID)
        REFERENCES MOVEMENT (ID),

    CONSTRAINT FK_MOV_CRYPTO_CRYPTOCURRENCY
        FOREIGN KEY (CRYPTOCURRENCY_ID)
        REFERENCES CRYPTOCURRENCY (ID)
);
