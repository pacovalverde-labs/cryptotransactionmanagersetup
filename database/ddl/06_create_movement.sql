
SET CURRENT SCHEMA CRYPTO;

-- ============================================================
-- MOVEMENT
-- ============================================================

CREATE TABLE MOVEMENT (
    ID BIGINT
        GENERATED ALWAYS AS IDENTITY
        PRIMARY KEY,

    BLOCKCHAIN_ID BIGINT,
    URL VARCHAR(2048),
    TX_HASH VARCHAR(255),
    MOVEMENT_TYPE VARCHAR(40),
    AUTO_DESCR VARCHAR(2000),
    USER_DESCR VARCHAR(2000),
    TX_TIMESTAMP TIMESTAMP,
    STATUS VARCHAR(30),
    FROM_ADDRESS VARCHAR(255),
    TO_ADDRESS VARCHAR(255),
    PROTOCOL_ID BIGINT,
    IMPORT_SOURCE_ID BIGINT,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT FK_MOVEMENT_BLOCKCHAIN
        FOREIGN KEY (BLOCKCHAIN_ID)
        REFERENCES BLOCKCHAIN (ID),

    CONSTRAINT FK_MOVEMENT_PROTOCOL
        FOREIGN KEY (PROTOCOL_ID)
        REFERENCES PROTOCOL (ID),

    CONSTRAINT FK_MOVEMENT_IMPORT_SOURCE
        FOREIGN KEY (IMPORT_SOURCE_ID)
        REFERENCES IMPORT_SOURCE (ID)
);
