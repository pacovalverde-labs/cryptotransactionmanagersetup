-- COMPROBACIÓN
-- ============================================================

SELECT
    C.ID,
    B.NAME AS BLOCKCHAIN,
    C.NAME,
    C.TICKER,
    C.CONTRACT_ADDRESS,
    C.DECIMALS,
    C.IS_NATIVE,
    C.ACTIVE
FROM CRYPTO.CRYPTOCURRENCY C
LEFT JOIN CRYPTO.BLOCKCHAIN B
    ON B.ID = C.BLOCKCHAIN_ID
ORDER BY
    COALESCE(B.NAME, 'ZZZ - SIN BLOCKCHAIN'),
    C.IS_NATIVE DESC,
    C.TICKER,
    C.NAME;
